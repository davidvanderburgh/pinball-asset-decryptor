ADVANCE = 4


def draw(img, x, y, text, colour):
    """Draw ``text`` with its top-left at (x, y + 1) (centred in an 8-pixel line)."""
    w, h = img.size
    for ch in text.upper():
        g = GLYPHS.get(ch)
        if g is not None:
            for r, row in enumerate(g):
                for c, bit in enumerate(row):
                    px, py = x + c, y + 1 + r
                    if bit == "#" and 0 <= px < w and 0 <= py < h:
                        img.putpixel((px, py), colour)
        x += ADVANCE
