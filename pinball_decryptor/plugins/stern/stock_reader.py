"""The game's own modes for any Spike 2 build: a hand table, or one generated from the program.

CONTRACT (title_reader calls this; keep the signature):

    ensure_table(elf, game, version, progress=None, cancel=None) -> TableResult

``progress(fraction, text)`` runs 0..1; ``cancel()`` returning True stops the work with
:class:`.title_reader.Cancelled`. The order is:

1. a HAND table (:mod:`.stock_mode_tables`) for this exact program - it always wins;
2. a table GENERATED earlier on this machine for this program (by its SHA-1);
3. a program :data:`KNOWN_STOCK` names (as Stern shipped it): a table generated NOW from it
   by the readers in :mod:`.stock_scan_cpp` (C++ rule titles) or :mod:`.stock_scan_c`
   (plain-C titles), a second or two cold, and saved - never another program's table;
4. any other program: the table of the same game and version when this program is that build
   with numbers this app changed in it (``stock_modes.identify``'s instruction or settings
   route) - a card the app already wrote is never read as stock;
5. a program holding this app's own text segment, or one that isn't the stock program of a
   build :data:`KNOWN_STOCK` names, whose original hasn't been read: refused, with a note
   asking for the original card once;
6. a build the app doesn't know at all: read, and the notes say its numbers are the card's.

Generated tables are kept in :func:`user_tables_dir` as ``<sha1>.r<READER_REV>.txt`` with an
``index.json`` keyed by the program's SHA-1 (every kept table is listed, so two programs of
one build never displace each other), and :func:`.stock_modes.tables` lists them after the
hand tables - tables read from a known stock program first - so ``table_for``, ``identify``
and every caller of those (the tab's dialog, the Write scan, the engine's Write) see them
with no change. Raising :data:`READER_REV` makes every older generated table stale: it is
generated again the next time its card is read.

A STOCK PROGRAM. A table records the numbers it reads as the game's own, so it must be read
from a program as Stern shipped it. A Write of the game's own numbers changes only
instruction words and setting defaults, so a written card has no mark of its own: what tells
it apart is that its SHA-1 isn't the one :data:`KNOWN_STOCK` lists for its build (step 5).
"""

import hashlib
