INDEX = "index.json"
INDEX_FORMAT = 2
NO_MODES = "No modes of the game's own were found in this game program."
#: the caveat of a table read from a program the app has not seen from Stern
UNKNOWN_BUILD = ("This build isn't one the app has seen from Stern, so the numbers shown as the "
                 "game's own are the ones on this card.")


@dataclass
class TableResult:
    build: object = None      # a stock_modes.Build, or None
    origin: str = ""          # "hand" | "generated" | ""
    notes: tuple = ()


def user_tables_dir():
    """Where tables generated on this machine are kept."""
    from .title_reader import cache_dir
    return cache_dir("stock_tables")


def table_path(sha1, rev=READER_REV):
    return os.path.join(user_tables_dir(), "%s.r%d.txt" % (sha1, rev))


# ---- generating --------------------------------------------------------------------------------
def generate(elf, game, version, progress=None, cancel=None):
    """``(table text, info)`` for the game program *elf* (bytes): the C++ reader on a title
    with a C++ rule manager, the plain-C reader otherwise. *info* = ``{"family", "modes",
    "rows", "seconds"}``. Raises :class:`.stock_scan.ScanError` when the program can't be
    read, :class:`.title_reader.Cancelled` when *cancel* says so."""
    from . import stock_scan as S
    from . import stock_scan_c, stock_scan_cpp
    from .title_reader import Cancelled
    say = progress or (lambda f, t="": None)
    t0 = time.monotonic()
    say(0.0, "Reading the game program")
    prog = S.Program(elf)
    if cancel is not None and cancel():
        raise Cancelled()
    say(0.03, "Reading the program's classes")
    model = S.class_model(prog)
    if stock_scan_cpp.family(model):
        reading = stock_scan_cpp.read(prog, model, step=lambda f, t="": say(0.05 + 0.9 * f, t),
                                      cancel=cancel)
    else:
        reading = stock_scan_c.read(prog, step=lambda f, t="": say(0.05 + 0.9 * f, t),
                                    cancel=cancel)
    seconds = time.monotonic() - t0
    head = ["generated by this app from the game program (reader revision %d, %s rules)"
            % (READER_REV, {"c": "plain-C"}.get(reading.family, reading.family))]
    text = S.table_text(game, version, prog.sha1, reading, head)
    info = {"family": reading.family, "modes": len(reading.modes),
            "rows": sum(len(m.rows) for m in reading.modes), "seconds": seconds}
    say(0.97, "Saving")
    return text, info


def stock_state(elf, sha1=None):
    """``("known" | "ours" | "unknown", words)``: whether *elf* is a program as Stern shipped
    it (a build this app knows), one this app changed (it holds the app's extension segment),
    or one it can't tell."""
    sha1 = sha1 or hashlib.sha1(elf).hexdigest()
    if sha1 in KNOWN_STOCK:
        return "known", "a build this app knows as Stern shipped it (%s)" % KNOWN_STOCK[sha1]
    from .progreloc import EXT_MAGIC
    if EXT_MAGIC in elf:
        return "ours", ("this card's game program was changed by this app (it holds the "
                        "app's own text segment)")
    return "unknown", "a build this app hasn't seen from Stern"


def known_build(game, version):
    """The ``"<game> <version>"`` of a build :data:`KNOWN_STOCK` names for this title and
    version (versions compared as the tables compare them: ``1.59`` is ``1.59.0``), or None."""
    from .stock_modes import version_key
    want = version_key(version)
    for name in KNOWN_STOCK.values():
        g, _sp, v = name.partition(" ")
        if g == game and version_key(v) == want:
            return name
    return None


# ---- the cache -------------------------------------------------------------------------------------
_LOCK = threading.RLock()
_CACHE = {"index_key": None, "builds": [], "parsed": {}}


def _index_file():
    return os.path.join(user_tables_dir(), INDEX)


def load_index():
    """``{sha1: {"game", "version", "rev", "stock", "made"}}`` (``{}`` on any trouble; an
    index of an older format lists nothing)."""
    try:
        with open(_index_file(), "r", encoding="utf-8") as f:
            data = json.load(f)
        if not isinstance(data, dict) or data.get("format") != INDEX_FORMAT:
            return {}
        builds = data.get("builds")
        return {k: v for k, v in builds.items() if isinstance(v, dict)} \
            if isinstance(builds, dict) else {}
    except (OSError, ValueError):
        return {}


def _write_atomic(path, text):
    tmp = "%s.%d.%d.tmp" % (path, os.getpid(), threading.get_ident())
    try:
        with open(tmp, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            try:
                os.remove(tmp)
            except OSError:
                pass


def save_table(text, game, version, sha1, stock):
    """Keep a generated table and list it in the index under its program's SHA-1. Raises
    OSError when the folder can't be written."""
    with _LOCK:
        os.makedirs(user_tables_dir(), exist_ok=True)
        _write_atomic(table_path(sha1), text)
        idx = load_index()
        idx[sha1] = {"game": game, "version": str(version), "rev": READER_REV, "stock": stock,
                     "made": time.strftime("%Y-%m-%d %H:%M:%S")}
        _write_atomic(_index_file(), json.dumps({"format": INDEX_FORMAT, "builds": idx},
                                                indent=1, sort_keys=True))
        _CACHE["index_key"] = None


def _parse_file(path):
    from . import stock_modes
    try:
        st = os.stat(path)
    except OSError:
        return None
    key = (st.st_mtime_ns, st.st_size)
    with _LOCK:
        got = _CACHE["parsed"].get(path)
        if got and got[0] == key:
            return got[1]
        try:
            with open(path, "r", encoding="utf-8") as f:
                builds = stock_modes.parse(f.read())
        except (OSError, ValueError, UnicodeDecodeError):
            builds = []
        b = builds[0] if len(builds) == 1 else None
        _CACHE["parsed"][path] = (key, b)
        return b


def cached_builds():
    """Every generated table of the current revision listed in the index, as
    :class:`.stock_modes.Build` (parsed once per file change). ``[]`` on any trouble."""
    try:
        path = _index_file()
        st = os.stat(path)
        key = (path, st.st_mtime_ns, st.st_size)
    except OSError:
        return []
    with _LOCK:
        if _CACHE["index_key"] == key:
            return list(_CACHE["builds"])
        out = []
        idx = load_index()
        # a table read from a program Stern shipped comes before one read from a program the
        # app doesn't know, so the first table of a title and version is the stock one
        for sha1 in sorted(idx, key=lambda k: (idx[k].get("stock") != "known",
                                               str(idx[k].get("game")), k)):
            if idx[sha1].get("rev") != READER_REV:
                continue
            b = _parse_file(table_path(sha1))
            if b is not None and b.sha1 == sha1 and b.modes:
                out.append(b)
        _CACHE["index_key"], _CACHE["builds"] = key, out
        return list(out)


def cached_table(sha1):
    """The generated table for this program, when one of the current revision is kept."""
    b = _parse_file(table_path(sha1))
    return b if b is not None and b.sha1 == sha1 else None


def older_tables(sha1):
    """The tables OLDER readers kept for this program (``<sha1>.r<rev>.txt`` below
    :data:`READER_REV`, newest first). A project's staged row keys are read through them
    after an app update raised the revision (``stock_modes.resolve_keys``), so they are
    never deleted by a newer reader."""
    out = []
    for rev in range(READER_REV - 1, 0, -1):
        b = _parse_file(table_path(sha1, rev))
        if b is not None and b.sha1 == sha1:
            out.append(b)
    return out


# ---- the operator menu's words for a table's settings ---------------------------------------------
def captions_for(elf, build, sha1=None):
    """``{AD_NAME: caption}``: what the operator menu prints for each setting *build*'s rows
    name (``adjustments.menu_label``: the Defaults tab's words), read from the game program
    *elf* once and kept beside the tables as ``<sha1>.captions.json``. ``{}`` on any trouble
    (the tab then words a setting from its name)."""
    if build is None:
        return {}
    names = sorted(build.adjustment_numbers())
    if not names:
        return {}
    sha1 = sha1 or hashlib.sha1(bytes(elf)).hexdigest()
    path = os.path.join(user_tables_dir(), "%s.captions.json" % sha1)
    try:
        with open(path, "r", encoding="utf-8") as f:
            kept = json.load(f)
        if isinstance(kept, dict) and all(n in kept for n in names):
            return {n: str(kept[n]) for n in names if kept[n]}
    except (OSError, ValueError):
        pass
    try:
        from . import adjustments as A
        table = A.AdjustmentTable(bytes(elf))
        out = {n: A.menu_label(table, table.by_name[n]) for n in names if n in table.by_name}
    except Exception:                               # noqa: BLE001 - words only
        return {}
    try:
        _write_atomic(path, json.dumps({n: out.get(n, "") for n in names}, indent=1,
                                       sort_keys=True))
    except OSError:
        pass
    return {n: c for n, c in out.items() if c}


# ---- the contract ----------------------------------------------------------------------------------
def ensure_table(elf, game, version, progress=None, cancel=None):
    """:class:`TableResult` for the game program *elf*: hand table, cached table, a table
    generated from a stock program, the original's table for a card this app changed, or a
    note saying why there is none (see the module)."""
    from . import stock_modes as SM
    from .stock_scan import ScanError
    from .title_reader import Cancelled
    say = progress or (lambda f, t="": None)

    def check():
        if cancel is not None and cancel():
            raise Cancelled()

    def done(result):
        say(1.0, "")
        return result

    elf = bytes(elf)
    sha1 = hashlib.sha1(elf).hexdigest()
    say(0.0, "Looking for this build's table")
    hand = SM.hand_tables()
    for b in hand:
        if b.sha1 == sha1:
            return done(TableResult(build=b, origin="hand"))
    try:
        img = SM.ElfImage(elf)
    except (SM.StockModeError, ValueError, struct.error) as e:
        return done(TableResult(notes=("The game program can't be read: %s." % e,)))
    state, why = stock_state(elf, sha1)
    b = cached_table(sha1)
    if b is not None and state != "known" and (state == "ours" or known_build(game, version)):
        # kept from a program that is not Stern's (one this app changed, or not the stock
        # program of a build the app now knows): never served as the game's own numbers;
        # the original's table or the refusal below decides
        b = None
    if b is not None:
        if not b.modes:
            return done(TableResult(notes=(NO_MODES,)))
        if sha1 not in load_index():
            # a table kept without its index line (the index was lost): list it again
            try:
                with open(table_path(sha1), "r", encoding="utf-8") as f:
                    save_table(f.read(), game, version, sha1, state)
            except OSError:
                pass
        # the caveat of a program the app has not seen from Stern stays with its table
        return done(TableResult(build=b, origin="generated",
                                notes=(UNKNOWN_BUILD,) if state == "unknown" else ()))
    check()
    if state != "known":
        # a card this app already wrote numbers into: the table of its original
        # (never this very program's own kept table: that is not its original's)
        cands = [x for x in hand + cached_builds() if x.same_title(game, version)
                 and x.sha1 != sha1]
        if cands:
            found, _how, _why = SM.identify(img, cands, game, version)
            if found is not None:
                return done(TableResult(
                    build=found, origin="hand" if found in hand else "generated",
                    notes=("This card's game program holds numbers this app changed; the "
                           "table read from the original %s is used." % found.id,)))
        if state == "ours":
            return done(TableResult(notes=(
                "The game's own modes can't be read from this card: %s, so its numbers "
                "aren't the game's own. Open the original card once to read them." % why,)))
        known = known_build(game, version)
        if known is not None:
            return done(TableResult(notes=(
                "The game's own modes can't be read from this card: its game program isn't "
                "the one Stern shipped as %s (it may hold numbers this app changed), so its "
                "numbers can't be taken as the game's own. Open the original %s card once, "
                "then this one." % (known, known),)))
    check()
    try:
        text, info = generate(elf, game, version,
                              progress=lambda f, t="": say(0.02 + 0.95 * f, t), cancel=cancel)
    except (ScanError, ValueError, struct.error, IndexError) as e:
        return done(TableResult(notes=("The game's own modes can't be read from this game "
                                       "program: %s." % e,)))
    check()
    notes = []
    try:
        save_table(text, game, version, sha1, state)
        b = cached_table(sha1)
    except OSError as e:
        notes.append("The table couldn't be kept on this computer (%s); it is read again "
                     "next time." % (e.strerror or e))
        builds = SM.parse(text)
        b = builds[0] if builds else None
    if not info["modes"] or b is None:
        return done(TableResult(notes=tuple([NO_MODES] + notes)))
    notes.insert(0, "Read %d of the game's own modes from the program in %.1f s." % (
        info["modes"], info["seconds"]))
    if state == "unknown":
        notes.append(UNKNOWN_BUILD)
    return done(TableResult(build=b, origin="generated", notes=tuple(notes)))
