"""Regenerate ``pinball_decryptor/plugins/pinmame_classic/sam_games.py``.

Reads PinMAME's ``src/wpc/sam.c`` (Stern S.A.M., 2006-2014) and writes the
SAM game table: per title, every romset PinMAME knows with the one ``.bin``
it loads (file name, CRC32, size).  Usage::

    python scripts/gen_sam_games.py path/to/sam.c
"""

import os
import re
import sys

# PinMAME family -> the title the app shows.  The boot-flash "game" is left
# out: it is the board's loader, not a game with a display to capture.
DISPLAY = {
    "wpt": "World Poker Tour",
    "scarn": "The Simpsons Kooky Carnival",
    "fg": "Family Guy",
    "potc": "Pirates of the Caribbean",
    "sman": "Spider-Man",
    "wof": "Wheel of Fortune",
    "shr": "Shrek",
    "ij4": "Indiana Jones",
    "bdk": "Batman: The Dark Knight",
    "csi": "CSI",
    "twenty4": "24",
    "nba": "NBA",
    "bbh": "Big Buck Hunter Pro",
    "im": "Iron Man",
    "trn": "TRON: Legacy",
    "tf": "Transformers",
    "avr": "Avatar",
    "rsn": "The Rolling Stones",
    "acd": "AC/DC",
    "xmn": "X-Men",
    "avs": "The Avengers",
    "mtl": "Metallica",
    "st": "Star Trek",
    "mt": "Mustang",
    "twd": "The Walking Dead",
    "smanve": "Spider-Man Vault Edition",
}
KEYS = {"twenty4": "twenty_four", "smanve": "spider_man_vault_edition"}

ROM = re.compile(r'^SAM1_ROM\w+\(\s*(\w+)\s*,\s*"([^"]+)"\s*,\s*CRC\((\w+)\)'
                 r'.*?,\s*(0x[0-9A-Fa-f]+|\d+)\s*\)')
DEF = re.compile(r'^CORE_GAMEDEF\(\s*(\w+)\s*,\s*(\w+)\s*,\s*"([^"]+)"\s*,'
                 r'\s*(\d+)')
CLONE = re.compile(r'^CORE_CLONEDEF\(\s*(\w+)\s*,\s*(\w+)\s*,\s*\w+\s*,'
                   r'\s*"([^"]+)"\s*,\s*(\d+)')
DEFNV = re.compile(r'^CORE_(?:GAME|CLONE)DEFNV\(\s*(\w+)\s*,(?:\s*\w+\s*,)?'
                   r'\s*"([^"]+)"\s*,\s*(\d+)')


def tidy(title):
    """PinMAME's catalogue name as people say it: "Avengers, The Limited
    Edition (V1.7)" -> "The Avengers Limited Edition (V1.7)"; the "(Stern)"
    that tells Star Trek from Williams' goes."""
    title = re.sub(r"^(.*?), The\b", r"The \1", title)
    return title.replace(" (Stern)", "")


def family_of(romset):
    return "scarn" if romset.startswith("scarn") else romset.split("_")[0]


def main(src, out):
    roms, defs = {}, {}
    for line in open(src, encoding="latin-1"):
        line = line.strip()
        m = ROM.match(line)
        if m:
            roms[m.group(1)] = (m.group(2), int(m.group(3), 16),
                                int(m.group(4), 0))
            continue
        m = DEF.match(line) or CLONE.match(line)
        if m:
            defs["%s_%s" % (m.group(1), m.group(2))] = (m.group(3),
                                                        int(m.group(4)))
            continue
        m = DEFNV.match(line)
        if m:
            defs[m.group(1)] = (m.group(2), int(m.group(3)))
    games = {}
    for romset, (title, year) in defs.items():
        fam = family_of(romset)
        # Not in roms = a NO_DUMP entry (the community "Colored MOD"
        # romsets): no file anyone could hold, so nothing to match.
        if fam not in DISPLAY or romset not in roms:
            continue
        g = games.setdefault(fam, {"romsets": {}, "year": year})
        g["year"] = min(g["year"], year)
        g["romsets"][romset] = roms[romset] + (tidy(title),)
    missing = sorted(r for r in roms if r not in defs
                     and not r.startswith("sam1_flashb"))
    if missing:
        sys.exit("romsets with no game definition: %s" % missing)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write('"""Stern S.A.M. (2006-2014) game database.\n\n'
                "Generated by ``scripts/gen_sam_games.py`` from PinMAME's\n"
                "``src/wpc/sam.c``; do not edit by hand.  A SAM game is one\n"
                "``.bin`` (Stern's USB code update file, which is also the\n"
                "PinMAME ROM).  ``romsets`` maps every PinMAME romset of the\n"
                "title to ``(file, crc32, size, title)``: the ``.bin`` name\n"
                "PinMAME loads, its CRC32 and byte size, and PinMAME's name\n"
                'for that version.  See :mod:`.sam`.\n"""\n\n'
                "SAM_GAME_DB = {\n")
        for fam in sorted(games, key=lambda k: DISPLAY[k].lower()):
            g = games[fam]
            key = KEYS.get(fam) or re.sub(
                r"[^a-z0-9]+", "_", DISPLAY[fam].lower()).strip("_")
            f.write("    %r: {\n" % key)
            f.write("        \"display\": %r,\n" % DISPLAY[fam])
            f.write("        \"family\": %r,\n" % fam)
            f.write("        \"manufacturer\": 'Stern',\n")
            f.write("        \"year\": %d,\n" % g["year"])
            f.write("        \"dmd\": '128x32',\n")
            f.write("        \"romsets\": {\n")
            for rs in sorted(g["romsets"]):
                fn, crc, size, title = g["romsets"][rs]
                f.write("            %r: (%r, 0x%08x, %d, %r),\n"
                        % (rs, fn, crc, size, title))
            f.write("        },\n    },\n")
        f.write("}\n")
    print("%d titles, %d romsets -> %s" % (
        len(games), sum(len(g["romsets"]) for g in games.values()), out))


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    main(sys.argv[1], os.path.join(
        here, "..", "pinball_decryptor", "plugins", "pinmame_classic",
        "sam_games.py"))
